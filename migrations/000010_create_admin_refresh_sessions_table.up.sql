CREATE TABLE admin_refresh_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    replaced_by_hash VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT admin_refresh_sessions_admin_id_fkey
        FOREIGN KEY (admin_id) REFERENCES admins (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX admin_refresh_sessions_token_hash_unique
    ON admin_refresh_sessions (token_hash);

CREATE INDEX admin_refresh_sessions_admin_id_idx
    ON admin_refresh_sessions (admin_id);
