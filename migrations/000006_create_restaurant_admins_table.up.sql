CREATE TABLE restaurant_admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL,
    admin_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT restaurant_admins_restaurant_id_fkey
        FOREIGN KEY (restaurant_id) REFERENCES restaurants (id) ON DELETE CASCADE,
    CONSTRAINT restaurant_admins_admin_id_fkey
        FOREIGN KEY (admin_id) REFERENCES admins (id) ON DELETE CASCADE,
    CONSTRAINT restaurant_admins_role_id_fkey
        FOREIGN KEY (role_id) REFERENCES roles (id),
    CONSTRAINT restaurant_admins_restaurant_id_admin_id_key
        UNIQUE (restaurant_id, admin_id)
);

-- UNIQUE (restaurant_id, admin_id) already supports lookups by restaurant_id (leftmost column).
-- Separate index for looking up restaurants by admin.
CREATE INDEX restaurant_admins_admin_id_idx ON restaurant_admins (admin_id);
